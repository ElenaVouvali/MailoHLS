def check_semantic_fixture(name, graph):
    """Independently specified small-program expectations, never builder rules."""
    checks=[]
    def check(description, passed): checks.append({'description':description,'passed':bool(passed)})
    def access(point, evidence='all'):
        return [r for r in get_action_point_relations(graph,point,evidence) if r['relation_type']=='memory_access']
    returned=[a['return_root_evidence'] for _,a in graph.nodes(data=True) if a.get('return_root_evidence')]
    if name=='returned_alias':
        check('Each returned alias retains exact call/result/return binding evidence',returned and all(r['bindings'] and r['all_returns_resolved'] for r in returned))
        check('Two calls retain distinct proven actual arrays', {r['neighbor'] for r in access('L9','proven')}=={'L1'} and {r['neighbor'] for r in access('L19','proven')}=={'L3'})
    elif name=='ambiguous_return':
        check('Multiple return roots remain possible',any(len(r['roots'])==2 and set(r['roots'].values())=={'possible'} for r in returned))
        check('Ambiguous returned pointer has no proven array access',not access('L9','proven'))
    elif name in ('unresolved_call','recursive_call'):
        check('Unresolved/recursive call effects remain possible',access('L9') and all(r['evidence_status']=='possible' for r in access('L9')))
        check('Unresolved call is not a concrete proven access',not access('L9','proven'))
    elif name=='index_and_state':
        outer,inner=get_loop_semantics(graph,'L9'),get_loop_semantics(graph,'L19')
        check('Upper-bound metadata stays separate from exact trip count',outer['metadata_value']==8 and outer['compiler_proven_trip_count']==7)
        check('Outer direct and descendant accesses are distinct', {'direct_body','nested_descendant'} <= {r['access_scope'] for r in outer['accesses']})
        check('SSA scalar loop state is retained',any(s['state_kind']=='scalar' for s in outer['ssa_state']+inner['ssa_state']))
        check('Memory dependence records carrying outer loop',any(d.get('carrying_loop')==outer['compiler_loop'] and d['evidence_status']=='proven' for d in outer['memory_dependences']))
        check('Index dataflow distinguishes one-IV and two-IV accesses', {1,2} <= {len(r['access_indices']['induction_loops']) for r in inner['accesses']})
    elif name=='different_indices':
        rows=access('L9'); operations={r['source_operation'] for r in rows}
        check('Same storage keeps distinct access maps',len({r['access_indices']['affine_map'] or str(r['access_indices']['ssa_operands']) for r in rows})>=2)
        check('Disjoint index ranges do not acquire a proven cross-access dependence',not any(e['relation_type']=='depends_on' and e['evidence_status']=='proven' and u!=v and {u,v}<=operations for u,v,e in graph.edges(data=True)))
    elif name=='registration':
        rows={r['action_id']:r for r in graph.graph['action_point_coverage']['records']}
        check('Unregistered source label has no active slot',rows['L3']['source_labeled'] and not rows['L3']['metadata_registered'] and not rows['L3']['compiler_matched'])
        check('Missing registered allocation is unresolved, without fabricated elimination proof',rows['L5']['metadata_registered'] and not rows['L5']['compiler_matched'] and rows['L5']['compiler_eliminated'] is None)
        check('Missing registered loop is not attached through an ordinal fallback',rows['L7']['metadata_registered'] and not rows['L7']['compiler_matched'] and 'action:L7' not in graph)
        check('Compiler exact count is not overwritten by upper-bound metadata',get_loop_semantics(graph,'L9')['compiler_proven_trip_count']==7)
    elif name=='strided_views':
        mappings=[e['view_mapping'] for _,_,e in graph.edges(data=True) if e['relation_type']=='references']
        check('Subview offsets/strides are compiler attributes relative to the source view',any(m['offset_semantics']=='relative_to_source_view' and m['offsets']==[16] and m['strides']==[2] for m in mappings))
        check('Reinterpret offsets are relative to underlying storage',any(m['offset_semantics']=='relative_to_underlying_storage' and m['offsets']==[0] for m in mappings))
        check('SCF scalar iter arguments/yields/results retain their owner',any(e['relation_type']=='loop_carried' and e.get('state_kind')=='scalar' and e.get('carrying_loop') for _,_,e in graph.edges(data=True)))
    if not checks: raise ValueError('No semantic expectations for '+name)
    return checks


def compile_semantic_fixtures(output, tools):
    """Compile source fixtures; explicitly label the one hand-authored IR case."""
    output=Path(output);output.mkdir(parents=True,exist_ok=True)
    specs=audit.HERE/'fixtures/semantics_v21.json'
    receipts={}
    for spec in json.loads(specs.read_text()):
        name=spec['name'];directory=output/name;directory.mkdir(parents=True,exist_ok=True)
        source,metadata,raw,path=[directory/f for f in ('kernel.cpp','kernel_info.txt','kernel.mlir','graph.json')]
        for file,text in ((source,spec['program']),(metadata,spec['metadata'])):
            if file.exists() and file.read_text()!=text: raise ValueError('Refusing to overwrite fixture input '+str(file))
            file.write_text(text)
        origin='handwritten_MLIR_native_verified' if 'mlir' in spec else 'source_compiled_by_pinned_cgeist'
        if 'mlir' in spec:
            raw.write_text(spec['mlir'])
            script=('import sys,json; from GNN_branch.mlir_graph_v2 import generate,digest,write_graph,validate; '
                'g,t=generate(sys.argv[1],sys.argv[2],sys.argv[3],provenance={"native_fixture":{"origin":"handwritten_MLIR_native_verified","mlir_sha256":digest(sys.argv[3])}},revision="2.1"); '
                'write_graph(g,sys.argv[4]); print(json.dumps({**validate(g),**t}))')
            command=[tools['python'],'-B','-c',script,str(source),str(metadata),str(raw),str(path)]
        else:
            command=[tools['python'],'-B','-m','GNN_branch.mlir_graph_v2','--revision','2.1','--source',str(source),
                     '--metadata',str(metadata),'--mlir-output',str(raw),'--cgeist',tools['cgeist'],'--output',str(path)]
        started=time.perf_counter()
        try:
            result=subprocess.run(command,cwd=c.ROOT,env={**os.environ,'PYTHONPATH':tools['pythonpath'],'PYTHONHASHSEED':'0'},capture_output=True,text=True,timeout=180)
            (directory/'native.log').write_text(result.stdout+'\n'+result.stderr)
            if result.returncode: raise RuntimeError(result.stderr[-4000:])
            graph=v2.read_graph(path);compact=v2.compact_view(graph)
            if v2.graph_payload(v2.expand_compact(compact))!=v2.graph_payload(graph) or _relations(graph)!=_relations(compact) or action_point_views(graph)!=action_point_views(compact):
                raise ValueError('Semantic fixture compaction changed evidence')
            checks=check_semantic_fixture(name,graph)
            checks.append({'description':'Exact compaction/reconstruction and query equality','passed':True})
            for _,attrs in graph.nodes(data=True):
                if attrs['category']=='action_point' and attrs['action_kind']=='loop':
                    if get_loop_semantics(graph,attrs['action_id'])!=get_loop_semantics(compact,attrs['action_id']):
                        raise ValueError('Compact fixture lost loop state/access scope')
            receipts[name]={'status':'checked','origin':origin,'checks':checks,'graph':c.display_path(path),
                'source_sha256':c.sha256(source),'metadata_sha256':c.sha256(metadata),'mlir_sha256':c.sha256(raw),
                'fixture_definition_sha256':c.sha256(specs),'graph_sha256':c.sha256(path),'command':command,
                'generation_seconds':time.perf_counter()-started,'native_metrics':json.loads(result.stdout.splitlines()[-1])}
        except (OSError,ValueError,RuntimeError,subprocess.TimeoutExpired) as exc:
            receipts[name]={'status':'blocked','origin':origin,'reason':str(exc),'checks':[]}
    return receipts


def run(args):
    output = c.repo_path(args.output_dir); output.mkdir(parents=True, exist_ok=True)
    if (output / 'manifest.json').exists():
        raise ValueError('Comparison already sealed; preserve it and choose a new output directory')
    if args.mode == 'fixtures':
        tools = old_relations.compiler_tools(build=args.polygeist_build,python=args.mlir_python)
        receipts = compile_semantic_fixtures(output,tools)
        c.write_json(output/'manifest.json',{'schema':'salt-hls-native-semantic-fixtures-v2.1','fixtures':receipts})
        print(json.dumps({name:{'status':r['status'],'passed_checks':sum(c['passed'] for c in r['checks']),'checks':len(r['checks']),'reason':r.get('reason')} for name,r in receipts.items()},indent=2))
        if any(r['status']!='checked' or not all(check['passed'] for check in r['checks']) for r in receipts.values()): raise SystemExit(2)
        return
    shared_path = c.repo_path(args.shared_manifest)
    shared = json.loads(shared_path.read_text()) if shared_path.is_file() else {}
    specs_path = audit.HERE / 'fixtures/annotations.json'
    specs = json.loads(specs_path.read_text())
    protected = {}
    existing_audit = audit.HERE / 'results/current/manifest.json'
    if existing_audit.is_file():
        data = json.loads(existing_audit.read_text())
        protected.update(data['inputs_sha256']); protected.update(data['protected_historical_sha256'])
    baseline_dir = c.repo_path(args.baseline_v2)
    baseline_records = {}
    if args.revision == '2.1' and (baseline_dir/'manifest.json').is_file():
        for path in baseline_dir.rglob('*'):
            if path.is_file(): protected[c.display_path(path)]=c.sha256(path)
        baseline_records=json.loads((baseline_dir/'comparison.json').read_text())['cases']
    code = {c.display_path(p): c.sha256(p) for p in [Path(__file__), Path(v2.__file__),
            c.ROOT/'GNN_branch/action_point_relations.py', c.ROOT/'tests/test_mlir_graph_v2.py', specs_path]}
    if args.revision == '2.1':
        for path in (c.ROOT/'GNN_branch/mlir_semantics.py',audit.HERE/'fixtures/semantics_v21.json'):
            code[c.display_path(path)]=c.sha256(path)
    records, annotations = {}, []
    try:
        tools = old_relations.compiler_tools(build=args.polygeist_build, python=args.mlir_python)
        blocker = None
    except FileNotFoundError as exc:
        tools, blocker = None, str(exc)
    cases = []
    for name in dict.fromkeys(args.kernels + list(audit.ORIGINALS if args.include_originals else ())):
        try:
            source, metadata, old_path, old, actions, projected = audit.load_kernel(name, shared)
            raw = audit.raw_artifacts(name, old_path, old)
            if not raw['raw_mlir']: raise FileNotFoundError('Matching raw MLIR unavailable; generate it with the pinned V1 pipeline')
            active_metadata = c.repo_path(projected['compiler_active_metadata_path']) if projected.get('compiler_active_metadata_path') else metadata
            cases.append((name, source, active_metadata, c.repo_path(raw['raw_mlir']), old_path,
                          {'actions': actions, 'projected': projected, 'source_metadata': metadata, 'old_graph': old}))
        except (OSError, ValueError) as exc:
            records[name] = {'status': 'blocked', 'reason': str(exc)}
    if args.include_fixtures:
        fixture_root = c.repo_path(args.fixture_dir)
        for name in FIXTURE_EXPECTATIONS:
            p = fixture_root / name
            if all((p / f).is_file() for f in ('kernel.cpp', 'kernel_info.txt', 'kernel.mlir', 'kernel.gexf')):
                cases.append(('fixture_' + name, p/'kernel.cpp', p/'kernel_info.txt', p/'kernel.mlir', p/'kernel.gexf', {'fixture': name}))
            else:
                records['fixture_' + name] = {'status': 'blocked', 'reason': 'Compiled R1.2 fixture unavailable; run structural_audit.audit --mode fixtures --compile-fixtures'}
    for name, source, metadata, mlir, old_path, context in cases:
        for path in (source, metadata, mlir, old_path): protected[c.display_path(path)] = c.sha256(path)
        if context.get('source_metadata'):
            protected[c.display_path(context['source_metadata'])] = c.sha256(context['source_metadata'])
        if not tools:
            records[name] = {'status': 'blocked', 'reason': blocker}; continue
        try:
            graph, rec = _compile_case(name, source, metadata, mlir, old_path, output, tools,args.revision)
            baseline_graph = None
            if args.revision == '2.1':
                previous=baseline_records.get(name)
                if previous and previous.get('status')=='compared':
                    for field, path in [('source_sha256',source),('metadata_sha256',metadata),('raw_mlir_sha256',mlir),('v1_graph_sha256',old_path)]:
                        if previous[field]!=c.sha256(path): raise ValueError('Baseline V2 context mismatch: '+field)
                    path=c.repo_path(previous['canonical_graph'])
                    if c.sha256(path)!=previous['canonical_graph_sha256']: raise ValueError('Baseline V2 graph integrity mismatch')
                    baseline_graph=v2.read_graph(path)
                    compact_path=c.repo_path(previous['compact_graph'])
                    if c.sha256(compact_path)!=previous['compact_graph_sha256']:raise ValueError('Baseline V2 compact integrity mismatch')
                    previous['statistics'][1:3]=[_stats(baseline_graph,'V2',path),_stats(v2.read_graph(compact_path),'compact V2',compact_path)]
                    rec['baseline_v2_receipt']=c.display_path(baseline_dir/'manifest.json')
                else:
                    baseline_graph,previous=_compile_case(name,source,metadata,mlir,old_path,output/'baseline_v2',tools)
                    rec['baseline_v2_receipt']='regenerated_revision_2.0; use original Git commit for byte-identical historical provenance'
                rec['statistics']=rec['statistics'][:1]+previous['statistics'][1:3]+rec['statistics'][1:]
                rec['baseline_v2_timing']=previous['timing']
            if 'fixture' in context:
                checks = []
                for point, neighbor, kind, expected, role in FIXTURE_EXPECTATIONS[context['fixture']]:
                    matches = [r for r in get_action_point_relations(graph, point) if r['neighbor'] == neighbor and r['relation_type'] == kind]
                    checks.append({'action_point': point, 'neighbor': neighbor, 'type': kind, 'expected': expected,
                        'passed': bool(matches) == expected and (not expected or any(role in (r.get('access_path'), r.get('hierarchy'), r.get('dependence_direction')) for r in matches)),
                        'compiler_evidence': matches})
                rec['fixture_checks'] = checks
            else:
                rec['source_action_point_count'] = len(context['actions'])
                rec['compiler_inactive_action_points'] = context['projected']['inactive_actions']
                if args.revision=='2.1':
                    coverage=graph.graph['action_point_coverage']['records']
                    rec['compiler_inactive_action_points']=[r['action_id'] for r in coverage if r['metadata_registered'] and not r['compiler_matched']]
                    rec['source_only_labels']=[r['action_id'] for r in coverage if not r['metadata_registered']]
                rec['target_binding_rules'] = dict(Counter(a.get('target_binding_rule') for _,a in graph.nodes(data=True) if a['category']=='action_point'))
                for spec in specs:
                    if spec['kernel'] != name: continue
                    old_row = audit.annotate(spec, source, context['old_graph'], context['actions'], context['projected'], c.sha256(old_path))
                    new_row = _annotation_v2(old_row, graph)
                    if baseline_graph is not None:
                        previous_row=_annotation_v2(old_row,baseline_graph)
                        new_row.update(baseline_v2_observed=previous_row['observed'],baseline_v2_evidence=previous_row['v2_evidence'])
                    new_row['v1_observed'] = old_row['observed']; annotations.append(new_row)
            records[name] = rec
        except (OSError, RuntimeError, ValueError, subprocess.TimeoutExpired) as exc:
            records[name] = {'status': 'blocked', 'reason': str(exc)}
    semantic_fixtures = compile_semantic_fixtures(output/'semantic_fixtures',tools) if args.revision=='2.1' and tools and not args.skip_semantic_fixtures else {}
    for path, expected in protected.items():
        if c.sha256(c.repo_path(path)) != expected: raise ValueError(f'Protected input changed: {path}')
    for path,expected in code.items():
        if c.sha256(c.repo_path(path))!=expected:raise ValueError('Code changed during comparison; start a fresh output: '+path)
    manifest = {'schema': 'salt-hls-v1-v2-comparison-v1', 'revision':args.revision, 'git_commit': subprocess.check_output(['git','rev-parse','HEAD'],cwd=c.ROOT,text=True).strip(),
                'worktree_status': subprocess.check_output(['git','status','--porcelain'],cwd=c.ROOT,text=True),
                'code_sha256': code, 'protected_inputs_sha256': protected, 'compiler_tools': tools,
                'kernels': args.kernels, 'include_originals': args.include_originals, 'include_fixtures': args.include_fixtures,
                'review_policy': 'Real-source annotations are drafts; only explicitly independently reviewed labels support reviewed precision/recall'}
    c.write_json(output/'manifest.json', manifest)
    c.write_json(output/'comparison.json', {'cases': records, 'annotations': annotations,'semantic_fixtures':semantic_fixtures,
        'v2_reference_metrics': audit.compare_annotations(annotations),
        'v1_reference_metrics': audit.compare_annotations([{**r, 'observed': r['v1_observed']} for r in annotations])})
    report(output, manifest, records, annotations)
    if args.revision=='2.1': report_revision(output,records,annotations,semantic_fixtures)
    print(json.dumps({'output': c.display_path(output), 'cases': {k: r['status'] for k, r in records.items()},
                      'semantic_fixtures':{k:{'status':r['status'],'passed_checks':sum(c['passed'] for c in r['checks']),'checks':len(r['checks'])} for k,r in semantic_fixtures.items()},
                      'fixture_failures': sum(not check['passed'] for rec in records.values() for check in rec.get('fixture_checks', []))}, indent=2))
    if any(rec['status'] != 'compared' or any(not check['passed'] for check in rec.get('fixture_checks', [])) for rec in records.values()) or any(r['status']!='checked' or not all(c['passed'] for c in r['checks']) for r in semantic_fixtures.values()):
        raise SystemExit(2)


