def _stats(graph, kind, path):
    if kind == 'V1':
        nodes = Counter(str(a.get('type')) for _, a in graph.nodes(data=True))
        edges = Counter(str(a.get('flow')) for _, _, a in graph.edges(data=True))
    else:
        report = v2.validate(graph); nodes, edges = report['node_categories'], report['edge_categories']
    schema = c.ROOT/'Checkpoints/gnn_final_absolute_direct_rank_s123/run1/provenance/feature_schema.json'
    recorded = json.loads(schema.read_text()) if schema.is_file() else {}
    legacy = None
    if kind=='V1':
        access=set()
        for u,v,e in graph.edges(data=True):
            if int(e.get('flow',-1))!=10 or e.get('role') not in ('read','write','readwrite'):continue
            op,root=(u,v) if graph.nodes[u].get('op_uid') else (v,u)
            if graph.nodes[op].get('text') in ('func.call','llvm.call','func.call_indirect'):continue
            access.add((op,root,e['role'],e.get('operand_index')))
        legacy={'memory_objects':'not first-class','legacy_storage_roots':sum(bool(a.get('is_memory_root')) for _,a in graph.nodes(data=True)),
            'concrete_accesses':len(access),'dependencies':{'proven':sum(int(e.get('flow',-1))==12 and e.get('role') in ('RAW','WAR','WAW') and e.get('certainty')=='proven' for _,_,e in graph.edges(data=True)), 'possible':'summary-only'},
            'call_bindings':sum(e.get('role')=='actual_to_formal' for _,_,e in graph.edges(data=True)),
            'note':'V1 root/access facts are context-insensitive; uncertainty summary edges are not exact pair counts'}
    return {'variant': kind, 'nodes': len(graph), 'edges': graph.number_of_edges(),
            'node_categories': dict(nodes), 'edge_categories': dict(edges),
            'serialized_bytes': Path(path).stat().st_size,
            'feature_tensor_dimensions': {k: recorded.get(k + '_feature_dim') for k in ('node','edge')} if kind == 'V1' else None,
            'encoding_note': 'V1 checkpoint schema' if kind == 'V1' else 'Typed attributes only; V1 tensors/weights are incompatible',
            'semantic_counts': semantic_counts(graph) if kind != 'V1' else legacy}


def semantic_counts(graph):
    edges = list(graph.edges(data=True))
    values = [a for _, a in graph.nodes(data=True) if a['category']=='ssa_value' and a.get('is_memory')]
    loops = {a['action_id']:get_loop_semantics(graph,a['action_id']) for _,a in graph.nodes(data=True)
             if a['category']=='action_point' and a['action_kind']=='loop'}
    return {'memory_objects':sum(a['category']=='memory_object' for _,a in graph.nodes(data=True)),
        'concrete_accesses':sum(e['relation_type']=='memory_access' for _,_,e in edges),
        'dependencies':dict(Counter(e['evidence_status'] for _,_,e in edges if e['relation_type']=='depends_on')),
        'proven_carrying_loops':dict(Counter(e['carrying_loop'] for _,_,e in edges if e['relation_type']=='depends_on' and e.get('carrying_loop'))),
        'call_bindings':sum(e['relation_type']=='actual_to_formal' for _,_,e in edges),
        'root_resolution':dict(Counter(a.get('root_resolution','not_recorded') for a in values)),
        'action_point_coverage':graph.graph.get('action_point_coverage'),
        'access_scope_query_counts':dict(Counter(r.get('access_scope','not_recorded') for loop in loops.values() for r in loop['accesses'])),
        'loop_trip_counts':{label:{k:loop[k] for k in ('metadata_value','compiler_proven_trip_count','trip_count_provenance')} for label,loop in loops.items()},
        'carrying_loop_annotation_status':'available' if graph.graph['schema']==v2.SCHEMA_V21 else 'not_recorded',
        'scalar_state_edges':sum(e['relation_type']=='loop_carried' and e.get('state_kind')=='scalar' for _,_,e in edges) if graph.graph['schema']==v2.SCHEMA_V21 else None}


def _relations(graph):
    cache = {}
    return {a['action_id']: get_action_point_relations(graph, a['action_id'], 'all', _access_cache=cache)
            for _, a in sorted(graph.nodes(data=True)) if a['category'] == 'action_point'}


def _compile_case(name, source, metadata, mlir, old_path, output, tools, revision='2.0'):
    directory = output / 'graphs'; directory.mkdir(parents=True, exist_ok=True)
    canonical_path = directory / (name + ('.v2.json' if revision=='2.0' else '.v21.json'))
    compact_path = directory / (name + ('.compact.json' if revision=='2.0' else '.compact.v21.json'))
    command = [tools['python'], '-B', '-m', 'GNN_branch.mlir_graph_v2', '--source', str(source),
               '--metadata', str(metadata), '--mlir', str(mlir), '--v1-graph', str(old_path), '--output', str(canonical_path), '--revision',revision]
    env = {**os.environ, 'PYTHONPATH': tools['pythonpath'], 'PYTHONHASHSEED': '0'}
    result = subprocess.run(command, cwd=c.ROOT, env=env, capture_output=True, text=True, timeout=180)
    if result.returncode:
        raise RuntimeError(f'Native V2 generation failed ({result.returncode}): {result.stderr[-4000:]}')
    native_metrics = json.loads(result.stdout.splitlines()[-1])
    graph, old = v2.read_graph(canonical_path), nx.read_gexf(old_path)
    old_values = {a['ssa_id'] for _, a in old.nodes(data=True) if a.get('ssa_id')}
    new_values = {a['ssa_id'] for _, a in graph.nodes(data=True) if a.get('ssa_id')}
    if old_values != new_values:
        raise ValueError('V1/V2 SSA identity preservation failed')
    def identity(attrs): return attrs.get('op_uid') or attrs.get('ssa_id')
    old_ssa = Counter((identity(old.nodes[u]), identity(old.nodes[v]), e['role'], int(e['position']))
        for u,v,e in old.edges(data=True) if int(e.get('flow', -1)) == 1 and e.get('role') in ('result','operand'))
    new_ssa = Counter((identity(graph.nodes[u]), identity(graph.nodes[v]), 'result' if e['relation_type']=='defines' else 'operand', int(e['legacy_evidence']['position']))
        for u,v,e in graph.edges(data=True) if e['relation_type'] in ('defines','operand'))
    if old_ssa != new_ssa:
        raise ValueError('V1/V2 SSA use-def edge preservation failed')
    old_cfg = Counter((identity(old.nodes[u]),identity(old.nodes[v]),e.get('role'))
                      for u,v,e in old.edges(data=True) if int(e.get('flow',-1))==0)
    new_cfg = Counter((identity(graph.nodes[u]),identity(graph.nodes[v]),e['legacy_evidence'].get('role'))
                      for u,v,e in graph.edges(data=True) if e['relation_type'] in ('next_operation','control_flow'))
    if old_cfg != new_cfg:
        raise ValueError('V1/V2 execution-order/CFG preservation failed')
    old_anchors = audit.semantic_anchors(old)
    new_points = {a['action_id'] for _,a in graph.nodes(data=True) if a['category']=='action_point'}
    if set(old_anchors) != new_points or any(len(nodes)!=1 for nodes in old_anchors.values()):
        raise ValueError('V1/V2 active action-point alignment differs')
    old_dep = {(old.nodes[u]['op_uid'],old.nodes[v]['op_uid'],e['role']) for u,v,e in old.edges(data=True)
               if int(e.get('flow',-1))==12 and e.get('certainty')=='proven'}
    new_dep = {(graph.nodes[v]['op_uid'],graph.nodes[u]['op_uid'],e['dependence_kind']) for u,v,e in graph.edges(data=True)
               if e['relation_type']=='depends_on' and e['evidence_status']=='proven'}
    if not old_dep <= new_dep:
        raise ValueError('V2 lost a proven V1 dependence')
    started = time.perf_counter(); compact = v2.compact_view(graph)
    compaction_seconds = time.perf_counter() - started
    v2.write_graph(compact, compact_path)
    restored = v2.expand_compact(v2.read_graph(compact_path))
    if v2.canonical_json(v2.graph_payload(restored)) != v2.canonical_json(v2.graph_payload(graph)):
        raise ValueError('Compaction cannot reconstruct canonical graph exactly')
    canonical_relations, compact_relations = _relations(graph), _relations(compact)
    if canonical_relations != compact_relations or action_point_views(graph) != action_point_views(compact):
        raise ValueError('Compact view changed action-point relationship semantics')
    for point in new_points:
        if graph.nodes['action:'+point]['action_kind']=='loop' and get_loop_semantics(graph,point)!=get_loop_semantics(compact,point):
            raise ValueError('Compact view changed loop semantics')
    # Record preserved facts independently of node counts.
    ssa = {n for n, a in graph.nodes(data=True) if a['category'] == 'ssa_value'}
    if not ssa <= set(compact): raise ValueError('Compaction removed SSA values')
    return graph, {'status': 'compared', 'source': c.display_path(source), 'metadata': c.display_path(metadata),
        'raw_mlir': c.display_path(mlir), 'v1_graph': c.display_path(old_path),
        'source_sha256': c.sha256(source), 'metadata_sha256': c.sha256(metadata),
        'raw_mlir_sha256': c.sha256(mlir), 'v1_graph_sha256': c.sha256(old_path),
        'canonical_graph': c.display_path(canonical_path), 'compact_graph': c.display_path(compact_path),
        'canonical_graph_sha256': c.sha256(canonical_path), 'compact_graph_sha256': c.sha256(compact_path),
        'statistics': [_stats(old, 'V1', old_path), _stats(graph, 'V2' if revision=='2.0' else 'V2.1', canonical_path), _stats(compact, 'compact V2' if revision=='2.0' else 'compact V2.1', compact_path)],
        'timing': {**{k: v for k, v in native_metrics.items() if 'seconds' in k}, 'compaction_seconds': compaction_seconds},
        'preservation': {'exact_canonical_reconstruction': True, 'all_evidence_queries_identical': True,
                         'all_derived_views_identical': True, 'ssa_nodes_retained': len(ssa),
                         'v1_ssa_identities_equal': True, 'v1_ssa_use_def_equal': True,
                         'v1_execution_order_and_cfg_equal': True, 'v1_active_action_points_equal': True,
                         'all_v1_proven_dependences_preserved': True,
                         'additional_native_proven_dependences': sorted(new_dep-old_dep),
                         'folded_auxiliary_nodes': len(compact.graph['compaction_mapping'])},
        'active_action_points': sorted(canonical_relations, key=lambda s: int(s[1:])),
        'query_evidence_counts': dict(Counter(r['evidence_status'] for rows in canonical_relations.values() for r in rows)),
        'call_bindings': sum(e['relation_type'] == 'actual_to_formal' for _, _, e in graph.edges(data=True)),
        'explicit_call_identity_bindings': sum(e['relation_type'] == 'actual_to_formal' and bool(e.get('call_uid')) for _, _, e in graph.edges(data=True)),
        'ssa_dataflow_edges': sum(e['relation_type'] in ('defines', 'operand') for _, _, e in graph.edges(data=True)),
        'concrete_access_count': sum(e['relation_type'] == 'memory_access' for _, _, e in graph.edges(data=True)),
        'unresolved_calls': [n for n,a in graph.nodes(data=True) if a.get('call_identity') and a.get('call_resolution')!='proven'],
        'compiler_dependence_status': dict(Counter(e['evidence_status'] for _, _, e in graph.edges(data=True) if e['relation_type'] == 'depends_on')),
        'unresolved_memory_values': [n for n, a in graph.nodes(data=True) if a['category'] == 'ssa_value' and a.get('root_resolution') in ('possible', 'not_established')],
        'compatibility_mapping_unresolved': [n for n, rec in graph.graph['compatibility_mapping'].items() if rec['target'] is None],
        'native_command': command, 'native_stdout': native_metrics}


def _annotation_v2(row, graph):
    point, neighbor = row['action_i'], row['action_j']
    if 'action:' + point not in graph or 'action:' + neighbor not in graph:
        coverage = graph.graph.get('action_point_coverage',{}).get('records',[])
        unregistered = any(r['action_id'] in (point,neighbor) and not r['metadata_registered'] for r in coverage)
        return {**row, 'observed': None, 'v2_evidence': [], 'v2_status': 'not_registered' if unregistered else 'inactive_action_point'}
    kind = {'loop_array_access': 'memory_access', 'nearest_child_loop': 'loop_hierarchy',
            'dependence_forward': 'memory_dependence'}[row['relationship_type']]
    matches = [r for r in get_action_point_relations(graph, point, 'all') if r['neighbor'] == neighbor and r['relation_type'] == kind]
    if kind == 'loop_hierarchy': matches = [r for r in matches if r['hierarchy'] == 'child']
    if kind == 'memory_dependence': matches = [r for r in matches if r['dependence_direction'] == 'precedes']
    proven = any(r['evidence_status'] == 'proven' for r in matches)
    return {**row, 'observed': True if proven else None if matches else False,
            'v2_evidence': matches, 'v2_status': 'proven' if proven else 'possible' if matches else 'not_established'}


