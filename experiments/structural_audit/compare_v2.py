def _stats(graph, kind, path):
    if kind == 'V1':
        nodes = Counter(str(a.get('type')) for _, a in graph.nodes(data=True))
        edges = Counter(str(a.get('flow')) for _, _, a in graph.edges(data=True))
    else:
        report = v2.validate(graph); nodes, edges = report['node_categories'], report['edge_categories']
    schema = c.ROOT/'Checkpoints/gnn_final_absolute_direct_rank_s123/run1/provenance/feature_schema.json'
    recorded = json.loads(schema.read_text()) if schema.is_file() else {}
    return {'variant': kind, 'nodes': len(graph), 'edges': graph.number_of_edges(),
            'node_categories': dict(nodes), 'edge_categories': dict(edges),
            'serialized_bytes': Path(path).stat().st_size,
            'feature_tensor_dimensions': {k: recorded.get(k + '_feature_dim') for k in ('node','edge')} if kind == 'V1' else None,
            'encoding_note': 'V1 checkpoint schema' if kind == 'V1' else 'Typed attributes only; V1 tensors/weights are incompatible'}


def _relations(graph):
    cache = {}
    return {a['action_id']: get_action_point_relations(graph, a['action_id'], 'all', _access_cache=cache)
            for _, a in sorted(graph.nodes(data=True)) if a['category'] == 'action_point'}


def _compile_case(name, source, metadata, mlir, old_path, output, tools):
    directory = output / 'graphs'; directory.mkdir(parents=True, exist_ok=True)
    canonical_path, compact_path = directory / (name + '.v2.json'), directory / (name + '.compact.json')
    command = [tools['python'], '-B', '-m', 'GNN_branch.mlir_graph_v2', '--source', str(source),
               '--metadata', str(metadata), '--mlir', str(mlir), '--v1-graph', str(old_path), '--output', str(canonical_path)]
    env = {**os.environ, 'PYTHONPATH': tools['pythonpath'], 'PYTHONHASHSEED': '0'}
    result = subprocess.run(command, cwd=c.ROOT, env=env, capture_output=True, text=True, timeout=180)
    if result.returncode:
        raise RuntimeError(f'Native V2 generation failed ({result.returncode}): {result.stderr[-4000:]}')
    native_metrics = json.loads(result.stdout.splitlines()[-1])
    graph, old = v2.read_graph(canonical_path), nx.read_gexf(old_path)
    old_values = {a['ssa_id'] for _, a in old.nodes(data=True) if a.get('ssa_id')}
    new_values = {a['ssa_id'] for _, a in graph.nodes(data=True) if a.get('ssa_id')}
    if old_values != new_values:
        raise ValueError('V1/V2 SSA identity preservation failed')
    def identity(attrs): return attrs.get('op_uid') or attrs.get('ssa_id')
    old_ssa = Counter((identity(old.nodes[u]), identity(old.nodes[v]), e['role'], int(e['position']))
        for u,v,e in old.edges(data=True) if int(e.get('flow', -1)) == 1 and e.get('role') in ('result','operand'))
    new_ssa = Counter((identity(graph.nodes[u]), identity(graph.nodes[v]), 'result' if e['relation_type']=='defines' else 'operand', int(e['legacy_evidence']['position']))
        for u,v,e in graph.edges(data=True) if e['relation_type'] in ('defines','operand'))
    if old_ssa != new_ssa:
        raise ValueError('V1/V2 SSA use-def edge preservation failed')
    old_cfg = Counter((identity(old.nodes[u]),identity(old.nodes[v]),e.get('role'))
                      for u,v,e in old.edges(data=True) if int(e.get('flow',-1))==0)
    new_cfg = Counter((identity(graph.nodes[u]),identity(graph.nodes[v]),e['legacy_evidence'].get('role'))
                      for u,v,e in graph.edges(data=True) if e['relation_type'] in ('next_operation','control_flow'))
    if old_cfg != new_cfg:
        raise ValueError('V1/V2 execution-order/CFG preservation failed')
    old_anchors = audit.semantic_anchors(old)
    new_points = {a['action_id'] for _,a in graph.nodes(data=True) if a['category']=='action_point'}
    if set(old_anchors) != new_points or any(len(nodes)!=1 for nodes in old_anchors.values()):
        raise ValueError('V1/V2 active action-point alignment differs')
    old_dep = {(old.nodes[u]['op_uid'],old.nodes[v]['op_uid'],e['role']) for u,v,e in old.edges(data=True)
               if int(e.get('flow',-1))==12 and e.get('certainty')=='proven'}
    new_dep = {(graph.nodes[v]['op_uid'],graph.nodes[u]['op_uid'],e['dependence_kind']) for u,v,e in graph.edges(data=True)
               if e['relation_type']=='depends_on' and e['evidence_status']=='proven'}
    if not old_dep <= new_dep:
        raise ValueError('V2 lost a proven V1 dependence')
    started = time.perf_counter(); compact = v2.compact_view(graph)
    compaction_seconds = time.perf_counter() - started
    v2.write_graph(compact, compact_path)
    restored = v2.expand_compact(v2.read_graph(compact_path))
    if v2.canonical_json(v2.graph_payload(restored)) != v2.canonical_json(v2.graph_payload(graph)):
        raise ValueError('Compaction cannot reconstruct canonical graph exactly')
    canonical_relations, compact_relations = _relations(graph), _relations(compact)
    if canonical_relations != compact_relations or action_point_views(graph) != action_point_views(compact):
        raise ValueError('Compact view changed action-point relationship semantics')
    # Record preserved facts independently of node counts.
    ssa = {n for n, a in graph.nodes(data=True) if a['category'] == 'ssa_value'}
    if not ssa <= set(compact): raise ValueError('Compaction removed SSA values')
    return graph, {'status': 'compared', 'source': c.display_path(source), 'metadata': c.display_path(metadata),
        'raw_mlir': c.display_path(mlir), 'v1_graph': c.display_path(old_path),
        'source_sha256': c.sha256(source), 'metadata_sha256': c.sha256(metadata),
        'raw_mlir_sha256': c.sha256(mlir), 'v1_graph_sha256': c.sha256(old_path),
        'canonical_graph': c.display_path(canonical_path), 'compact_graph': c.display_path(compact_path),
        'canonical_graph_sha256': c.sha256(canonical_path), 'compact_graph_sha256': c.sha256(compact_path),
        'statistics': [_stats(old, 'V1', old_path), _stats(graph, 'V2', canonical_path), _stats(compact, 'compact V2', compact_path)],
        'timing': {**{k: v for k, v in native_metrics.items() if 'seconds' in k}, 'compaction_seconds': compaction_seconds},
        'preservation': {'exact_canonical_reconstruction': True, 'all_evidence_queries_identical': True,
                         'all_derived_views_identical': True, 'ssa_nodes_retained': len(ssa),
                         'v1_ssa_identities_equal': True, 'v1_ssa_use_def_equal': True,
                         'v1_execution_order_and_cfg_equal': True, 'v1_active_action_points_equal': True,
                         'all_v1_proven_dependences_preserved': True,
                         'additional_native_proven_dependences': sorted(new_dep-old_dep),
                         'folded_auxiliary_nodes': len(compact.graph['compaction_mapping'])},
        'active_action_points': sorted(canonical_relations, key=lambda s: int(s[1:])),
        'query_evidence_counts': dict(Counter(r['evidence_status'] for rows in canonical_relations.values() for r in rows)),
        'call_bindings': sum(e['relation_type'] == 'actual_to_formal' for _, _, e in graph.edges(data=True)),
        'explicit_call_identity_bindings': sum(e['relation_type'] == 'actual_to_formal' and bool(e.get('call_uid')) for _, _, e in graph.edges(data=True)),
        'ssa_dataflow_edges': sum(e['relation_type'] in ('defines', 'operand') for _, _, e in graph.edges(data=True)),
        'concrete_access_count': sum(e['relation_type'] == 'memory_access' for _, _, e in graph.edges(data=True)),
        'unresolved_calls': [n for n,a in graph.nodes(data=True) if a.get('call_identity') and a.get('call_resolution')!='proven'],
        'compiler_dependence_status': dict(Counter(e['evidence_status'] for _, _, e in graph.edges(data=True) if e['relation_type'] == 'depends_on')),
        'unresolved_memory_values': [n for n, a in graph.nodes(data=True) if a['category'] == 'ssa_value' and a.get('root_resolution') in ('possible', 'not_established')],
        'compatibility_mapping_unresolved': [n for n, rec in graph.graph['compatibility_mapping'].items() if rec['target'] is None],
        'native_command': command, 'native_stdout': native_metrics}


def _annotation_v2(row, graph):
    point, neighbor = row['action_i'], row['action_j']
    if 'action:' + point not in graph or 'action:' + neighbor not in graph:
        return {**row, 'observed': None, 'v2_evidence': [], 'v2_status': 'inactive_action_point'}
    kind = {'loop_array_access': 'memory_access', 'nearest_child_loop': 'loop_hierarchy',
            'dependence_forward': 'memory_dependence'}[row['relationship_type']]
    matches = [r for r in get_action_point_relations(graph, point, 'all') if r['neighbor'] == neighbor and r['relation_type'] == kind]
    if kind == 'loop_hierarchy': matches = [r for r in matches if r['hierarchy'] == 'child']
    if kind == 'memory_dependence': matches = [r for r in matches if r['dependence_direction'] == 'precedes']
    proven = any(r['evidence_status'] == 'proven' for r in matches)
    return {**row, 'observed': True if proven else None if matches else False,
            'v2_evidence': matches, 'v2_status': 'proven' if proven else 'possible' if matches else 'not_established'}


def report(output, manifest, records, annotations):
    lines = ['# V1–V2 structural graph comparison', '',
        'V2 is explicitly selected. No production graph, checkpoint, Stage-2 memory, inference, training or HLS result was modified.', '',
        '| Kernel / fixture | V1 nodes / edges | V2 canonical | V2 compact | Active action points |',
        '|---|---:|---:|---:|---:|']
    for name, rec in records.items():
        if rec['status'] != 'compared':
            lines.append(f'| {name} | blocked: {rec["reason"]} | | | |'); continue
        stats = rec['statistics']
        lines.append(f'| {name} | {stats[0]["nodes"]} / {stats[0]["edges"]} | {stats[1]["nodes"]} / {stats[1]["edges"]} | '
                     f'{stats[2]["nodes"]} / {stats[2]["edges"]} | {len(rec["active_action_points"])} |')
    real = {name:rec for name,rec in records.items() if rec['status']=='compared' and not name.startswith('fixture_')}
    metrics1 = audit.compare_annotations([{**r,'observed':r['v1_observed']} for r in annotations])
    metrics2 = audit.compare_annotations(annotations)
    lines += ['', '## Source references and coverage', '',
        '| Representation | Draft TP | Draft FP | Draft FN | Draft TN | Unresolved | Reviewed precision/recall |',
        '|---|---:|---:|---:|---:|---:|---|']
    for label,metrics in [('V1',metrics1),('V2',metrics2)]:
        counts = {key:sum(row[key] for row in metrics) for key in ('draft_TP','draft_FP','draft_FN','draft_TN','unresolved')}
        lines.append(f'| {label} | {counts["draft_TP"]} | {counts["draft_FP"]} | {counts["draft_FN"]} | '
                     f'{counts["draft_TN"]} | {counts["unresolved"]} | Unavailable without independent review |')
    lines += ['', '| Kernel | Source / active action points | Explicit call IDs / bindings | Unresolved memory values / calls | Unresolved V1 mappings |',
              '|---|---:|---:|---:|---:|']
    for name,rec in real.items():
        lines.append(f'| {name} | {rec.get("source_action_point_count")} / {len(rec["active_action_points"])} | '
                     f'{rec["explicit_call_identity_bindings"]} / {rec["call_bindings"]} | '
                     f'{len(rec["unresolved_memory_values"])} / {len(rec["unresolved_calls"])} | {len(rec["compatibility_mapping_unresolved"])} |')
    lines += ['', '## Serialized size and measured construction', '',
              '| Kernel | V1 bytes | V2 bytes | Compact bytes | Shared native/V1 builder seconds | Additional V2 seconds |',
              '|---|---:|---:|---:|---:|---:|']
    for name,rec in real.items():
        stats,timing = rec['statistics'],rec['timing']
        lines.append(f'| {name} | {stats[0]["serialized_bytes"]} | {stats[1]["serialized_bytes"]} | {stats[2]["serialized_bytes"]} | '
                     f'{timing["shared_native_analysis_and_v1_builder_seconds"]:.4f} | {timing["additional_v2_construction_seconds"]:.4f} |')
    lines += ['', '## Semantic checks', '',
        'The same hash-authenticated raw MLIR and native analysis extension are used for each pair. '
        'Call bindings come from live indexed operands/formals and unique operation UIDs, not source-line proximity or an argument-position fallback. '
        'Concrete access edges uniformly point from operation to memory object; call summaries are separate possible evidence. '
        'Formal roots stay local and are substituted only along the selected call chain.', '',
        'The 28 real-source annotations are machine-assisted drafts. Their disagreements and counts are diagnostic; '
        'reviewed precision/recall remain unavailable without independent adjudication. '
        '`not_established` is not proof of independence. Inactive compiler action points remain inactive.', '']
    for name, rec in records.items():
        if 'fixture_checks' in rec:
            lines.append(f'- {name}: {sum(r["passed"] for r in rec["fixture_checks"])} / {len(rec["fixture_checks"])} independently specified compiler-fixture checks passed.')
    for row in annotations:
        if row['kernel'] == 'GAN' and row['action_j'] == 'L11' and row['action_i'] in ('L2', 'L3'):
            lines += [f'- GAN {row["action_i"]}–L11: source expectation {row["expected"]}; V1 access={row["v1_observed"]}; '
                      f'V2 status={row["v2_status"]}; paths={sorted({r["access_path"] for r in row["v2_evidence"]})}. '
                      f'Concrete operations and exact call bindings are retained in comparison.json.']
    lines += ['', '## Compaction and information preservation', '',
        'Only leaf auxiliary shape/affine/trip-count nodes are folded into target attributes. '
        'Canonical-to-compact mappings include complete removed nodes and incident edges. '
        'Every successful comparison reconstructs canonical V2 exactly and returns identical typed queries and Boolean/legacy-bit views. '
        'SSA values, constants, call identities, memory evidence and dependencies are retained. '
        'Synthetic V1 block connectivity is replaced by real region/block ownership, not an unverified pseudo-node deletion.', '',
        'Native V1 GEXF and V2 JSON byte sizes use different serialization formats; do not interpret byte differences as topology alone. '
        'Historical V1 construction times are unavailable. Shared native-analysis/V1-builder time, additional V2 construction time '
        'and compaction time are measured separately, without inventing an old runtime.', '',
        '## Compatibility and remaining work', '',
        'The frozen V1 GNN uses 403 node and 82 edge features, and production action memory is 128-D. '
        'V2 provides deterministic typed attributes, not a compatible learned tensor encoder. V1 validators reject this schema; '
        'feeding V2 topology into V1 weights would not be a valid prediction experiment. Stage-2 still uses its unchanged Boolean V1 routing.', '',
        'Returned-memory aliases, recursive/unresolved calls, unresolved/partial aliases and unsupported native effects remain conservative. '
        'Analysis AP headers remain control/dataflow surrogates, not bit-accurate vendor fixed-point arithmetic. '
        'The complete native analysis record is retained, including no-dependence and unknown outcomes.', '',
        'Before selecting V2 for learning: independently review real annotations, extend adversarial call/view/region tests, '
        'implement a separate frozen V2 tensor schema, and compare V1, canonical V2 and compact V2 with the same kernel-family split, '
        'QoR data, target context, supervision, parameter budget and seeds. Report QoR prediction, ranking, feasibility and held-out kernel performance. '
        'No downstream predictive or synthesis advantage is claimed here.', '']
    (output / 'report.md').write_text('\n'.join(lines))


def run(args):
    output = c.repo_path(args.output_dir); output.mkdir(parents=True, exist_ok=True)
    if (output / 'manifest.json').exists():
        raise ValueError('Comparison already sealed; preserve it and choose a new output directory')
    shared_path = c.repo_path(args.shared_manifest)
    shared = json.loads(shared_path.read_text()) if shared_path.is_file() else {}
    specs_path = audit.HERE / 'fixtures/annotations.json'
    specs = json.loads(specs_path.read_text())
    protected = {}
    existing_audit = audit.HERE / 'results/current/manifest.json'
    if existing_audit.is_file():
        data = json.loads(existing_audit.read_text())
        protected.update(data['inputs_sha256']); protected.update(data['protected_historical_sha256'])
    code = {c.display_path(p): c.sha256(p) for p in [Path(__file__), Path(v2.__file__),
            c.ROOT/'GNN_branch/action_point_relations.py', c.ROOT/'tests/test_mlir_graph_v2.py', specs_path]}
    records, annotations = {}, []
    try:
        tools = old_relations.compiler_tools(build=args.polygeist_build, python=args.mlir_python)
        blocker = None
    except FileNotFoundError as exc:
        tools, blocker = None, str(exc)
    cases = []
    for name in dict.fromkeys(args.kernels + list(audit.ORIGINALS if args.include_originals else ())):
        try:
            source, metadata, old_path, old, actions, projected = audit.load_kernel(name, shared)
            raw = audit.raw_artifacts(name, old_path, old)
            if not raw['raw_mlir']: raise FileNotFoundError('Matching raw MLIR unavailable; generate it with the pinned V1 pipeline')
            active_metadata = c.repo_path(projected['compiler_active_metadata_path']) if projected.get('compiler_active_metadata_path') else metadata
            cases.append((name, source, active_metadata, c.repo_path(raw['raw_mlir']), old_path,
                          {'actions': actions, 'projected': projected, 'source_metadata': metadata, 'old_graph': old}))
        except (OSError, ValueError) as exc:
            records[name] = {'status': 'blocked', 'reason': str(exc)}
    if args.include_fixtures:
        fixture_root = c.repo_path(args.fixture_dir)
        for name in FIXTURE_EXPECTATIONS:
            p = fixture_root / name
            if all((p / f).is_file() for f in ('kernel.cpp', 'kernel_info.txt', 'kernel.mlir', 'kernel.gexf')):
                cases.append(('fixture_' + name, p/'kernel.cpp', p/'kernel_info.txt', p/'kernel.mlir', p/'kernel.gexf', {'fixture': name}))
            else:
                records['fixture_' + name] = {'status': 'blocked', 'reason': 'Compiled R1.2 fixture unavailable; run structural_audit.audit --mode fixtures --compile-fixtures'}
    for name, source, metadata, mlir, old_path, context in cases:
        for path in (source, metadata, mlir, old_path): protected[c.display_path(path)] = c.sha256(path)
        if context.get('source_metadata'):
            protected[c.display_path(context['source_metadata'])] = c.sha256(context['source_metadata'])
        if not tools:
            records[name] = {'status': 'blocked', 'reason': blocker}; continue
        try:
            graph, rec = _compile_case(name, source, metadata, mlir, old_path, output, tools)
            if 'fixture' in context:
                checks = []
                for point, neighbor, kind, expected, role in FIXTURE_EXPECTATIONS[context['fixture']]:
                    matches = [r for r in get_action_point_relations(graph, point) if r['neighbor'] == neighbor and r['relation_type'] == kind]
                    checks.append({'action_point': point, 'neighbor': neighbor, 'type': kind, 'expected': expected,
                        'passed': bool(matches) == expected and (not expected or any(role in (r.get('access_path'), r.get('hierarchy'), r.get('dependence_direction')) for r in matches)),
                        'compiler_evidence': matches})
                rec['fixture_checks'] = checks
            else:
                rec['source_action_point_count'] = len(context['actions'])
                rec['compiler_inactive_action_points'] = context['projected']['inactive_actions']
                rec['target_binding_rules'] = dict(Counter(a.get('target_binding_rule') for _,a in graph.nodes(data=True) if a['category']=='action_point'))
                for spec in specs:
                    if spec['kernel'] != name: continue
                    old_row = audit.annotate(spec, source, context['old_graph'], context['actions'], context['projected'], c.sha256(old_path))
                    new_row = _annotation_v2(old_row, graph)
                    new_row['v1_observed'] = old_row['observed']; annotations.append(new_row)
            records[name] = rec
        except (OSError, RuntimeError, ValueError, subprocess.TimeoutExpired) as exc:
            records[name] = {'status': 'blocked', 'reason': str(exc)}
    for path, expected in protected.items():
        if c.sha256(c.repo_path(path)) != expected: raise ValueError(f'Protected V1 input changed: {path}')
    manifest = {'schema': 'salt-hls-v1-v2-comparison-v1', 'git_commit': subprocess.check_output(['git','rev-parse','HEAD'],cwd=c.ROOT,text=True).strip(),
                'worktree_status': subprocess.check_output(['git','status','--porcelain'],cwd=c.ROOT,text=True),
                'code_sha256': code, 'protected_inputs_sha256': protected, 'compiler_tools': tools,
                'kernels': args.kernels, 'include_originals': args.include_originals, 'include_fixtures': args.include_fixtures,
                'review_policy': 'Real-source annotations are drafts; only explicitly independently reviewed labels support reviewed precision/recall'}
    c.write_json(output/'manifest.json', manifest)
    c.write_json(output/'comparison.json', {'cases': records, 'annotations': annotations,
        'v2_reference_metrics': audit.compare_annotations(annotations),
        'v1_reference_metrics': audit.compare_annotations([{**r, 'observed': r['v1_observed']} for r in annotations])})
    report(output, manifest, records, annotations)
    print(json.dumps({'output': c.display_path(output), 'cases': {k: r['status'] for k, r in records.items()},
                      'fixture_failures': sum(not check['passed'] for rec in records.values() for check in rec.get('fixture_checks', []))}, indent=2))
    if any(rec['status'] != 'compared' or any(not check['passed'] for check in rec.get('fixture_checks', [])) for rec in records.values()):
        raise SystemExit(2)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--kernels', nargs='+', default=['GAN', 'covariance', 'Kalman'])
    parser.add_argument('--output-dir', default=str(DEFAULT_OUTPUT))
    parser.add_argument('--shared-manifest', default=str(audit.DEFAULT_SHARED))
    parser.add_argument('--fixture-dir', default=str(audit.HERE/'results/current/fixtures'))
    parser.add_argument('--include-originals', action=argparse.BooleanOptionalAction, default=True)
    parser.add_argument('--include-fixtures', action=argparse.BooleanOptionalAction, default=True)
    parser.add_argument('--polygeist-build'); parser.add_argument('--mlir-python')
    run(parser.parse_args())


if __name__ == '__main__': main()
